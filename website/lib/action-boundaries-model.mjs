export function actionBoundaryFrame(id, phase) {
  if (!Object.hasOwn(ACTION_BOUNDARY_STAGES, id)) throw new RangeError('Unknown action diagram')
  const stages = ACTION_BOUNDARY_STAGES[id], bounded = clampPhase(phase, stages.length), stage = stageForPhase(bounded, stages.length)
  return { ...stages[stage], stage, phase: bounded }
}
export function approvalOutcome(status) {
  if (!['waiting', 'approved', 'denied', 'timeout'].includes(status)) throw new RangeError('Unknown approval status')
  return { execute: status === 'approved', observation: status === 'denied' || status === 'timeout' ? '拒否と理由を返す' : null }
}
export function retryBoundary(contract, { remaining = 1, retryable = true, repeated = false } = {}) {
  const states = { idempotent: ['同じ冪等キー', true], atomic: ['同一DBの原子操作', true], unknown: ['自動再送を止めて照合', false] }
  if (!Object.hasOwn(states, contract)) throw new RangeError('Unknown retry contract')
  const automaticRetry = states[contract][1] && remaining > 0 && retryable && !repeated
  return { label: !automaticRetry && contract !== 'unknown' ? '停止して上位へ通知' : states[contract][0], automaticRetry }
}
