export function agentConceptFrame(diagram, phase) {
  const definitions = AGENT_CONCEPT_STAGES[diagram]
  if (!definitions) throw new TypeError('Unknown agent concept diagram')
  const bounded = clampPhase(phase, definitions.length)
  const stage = stageForPhase(bounded, definitions.length)
  return { phase: bounded, stage, ...definitions[stage] }
}

export function toolExchange(stage, { permitted = true, success = true, next = false } = {}) {
  if (!Number.isInteger(stage) || stage < 0 || stage > 6) throw new RangeError('Unknown tool stage')
  const outcome = !permitted ? '検証拒否' : success ? '成功' : '実行失敗'
  return { execute: permitted && stage >= 3, outcome: stage >= 4 || (!permitted && stage >= 2) ? outcome : null,
    observation: stage >= 5 ? outcome : null, nextRequest: stage === 6 && next }
}

export function memoryPlacement(kind) {
  const placements = { current: ['短期記憶', '毎ターンの指示'], reference: ['外部＋読み出し', 'ときどき使う資料'],
    progress: ['永続化した作業状態', '計画・進捗・決定'], preference: ['長期記憶＋保存基準', '好み・ナレッジ'] }
  if (!Object.hasOwn(placements, kind)) throw new RangeError('Unknown memory kind')
  return placements[kind]
}
