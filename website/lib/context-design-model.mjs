export function contextDesignFrame(id, phase) {
  if (!Object.hasOwn(CONTEXT_DESIGN_STAGES, id)) throw new RangeError('Unknown context diagram')
  const stages = CONTEXT_DESIGN_STAGES[id], bounded = clampPhase(phase, stages.length)
  const stage = stageForPhase(bounded, stages.length)
  return { ...stages[stage], stage, phase: bounded }
}
export function budgetResponse(outcome) {
  const states = { summarized: ['古い履歴を要約', '予算内で再構成'], reduced: ['検索件数を減らす', '予算内で再構成'], overflow: ['まだ超過', '停止して報告'] }
  if (!Object.hasOwn(states, outcome)) throw new RangeError('Unknown budget outcome')
  return { steps: [...states[outcome]], stop: outcome === 'overflow' }
}
export function contextTransfer(mode) {
  if (!['invalid', 'waiting', 'permitted'].includes(mode)) throw new RangeError('Unknown transfer mode')
  return { validData: mode !== 'invalid', parentApproved: mode === 'permitted', execute: mode === 'permitted' }
}
export const RETAINED_CONTEXT = Object.freeze(['制約・要件', '決定と理由', '未解決点', '成果物の参照', '計画と現在地'])
export function compactionRetention(missing) {
  if (!['none', 'decisions', 'constraints'].includes(missing)) throw new RangeError('Unknown retention choice')
  const absent = { none: null, decisions: '決定と理由', constraints: '制約・要件' }[missing]
  return { retained: RETAINED_CONTEXT.filter(label => label !== absent), missing: absent, matched: absent === null }
}
export function preprocessingShape(kind) {
  const choices = { full: ['全文', '短い資料・正確な引用', '容量と希釈に注意'], excerpt: ['抜粋', '関連箇所を抽出', '抽出漏れに注意'], summary: ['要約', '概要を把握', '細部は原資料へ戻る'], structured: ['構造化', '表・キー値に加工', '前処理が必要'] }
  if (!Object.hasOwn(choices, kind)) throw new RangeError('Unknown preprocessing shape')
  return [...choices[kind]]
}
