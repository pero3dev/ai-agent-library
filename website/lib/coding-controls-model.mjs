export function codingControlFrame(id,phase){
  if(!Object.hasOwn(CODING_CONTROL_STAGES,id))throw new RangeError('Unknown coding control diagram')
  const stages=CODING_CONTROL_STAGES[id],bounded=clampPhase(phase,stages.length),stage=stageForPhase(bounded,stages.length)
  return {...stages[stage],stage,phase:bounded}
}
export function ruleDiscovery(cwd){
  if(!['root','web','ml'].includes(cwd))throw new RangeError('Unknown rule cwd')
  return {root:true,web:cwd==='web',ml:cwd==='ml',referenceInjectsDetail:false}
}
export function automationReadiness({patterned,verifiable,safeFailure}){
  return {unattendedCandidate:patterned===true&&verifiable===true&&safeFailure===true}
}
export function codingPermissionPath(mode,request){
  if(!['ask','allowlist','isolated'].includes(mode)||!['bounded','external','secret'].includes(request))throw new RangeError('Unknown coding permission path')
  const deny=request==='secret'
  return {deny,autoExecute:!deny&&request==='bounded'&&mode!=='ask',needsApproval:!deny&&(request==='external'||mode==='ask')}
}
