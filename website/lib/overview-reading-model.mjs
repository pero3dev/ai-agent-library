export function overviewFrame(id, phase) {
  if (!Object.hasOwn(OVERVIEW_STAGES, id)) throw new RangeError('Unknown overview diagram')
  const rows = OVERVIEW_STAGES[id]
  const bounded = clampPhase(phase, rows.length)
  const stage = stageForPhase(bounded, rows.length)
  return { ...rows[stage], stage, phase: bounded }
}
