export function reflectionTransition(reason) {
  if (!['continue', 'complete', 'limit', 'small'].includes(reason)) throw new RangeError('Unknown reflection condition')
  return { revise: reason === 'continue', stop: reason !== 'continue', label: { continue: '修正へ', complete: '完了条件', limit: '回数上限', small: '改善幅の条件' }[reason] }
}
export function planningTrigger(trigger) {
  if (!['step', 'failure', 'information'].includes(trigger)) throw new RangeError('Unknown planning trigger')
  return { label: { step: 'ステップ完了', failure: '失敗', information: '新情報' }[trigger], review: true, stateBeforeNextInput: true }
}
export function retrievalPath(kind) {
  const paths = {
    simple: { nodes: ['質問', '検索', '生成'], owner: 'コード', retrieval: true, feedback: false },
    workflow: { nodes: ['質問', '書き換え', '複数検索', '照合・計算', '生成'], owner: 'コード', retrieval: true, feedback: false },
    agentic: { nodes: ['質問', '次の判断', '検索ツール', '回答'], owner: 'モデル', retrieval: true, feedback: true },
    full: { nodes: ['知識ソース', '入力', '生成'], owner: 'コード', retrieval: false, feedback: false }
  }
  if (!Object.hasOwn(paths, kind)) throw new RangeError('Unknown retrieval path')
  return structuredClone(paths[kind])
}
export function delegatedExecution(approval) {
  if (!['waiting', 'approved', 'denied'].includes(approval)) throw new RangeError('Unknown approval')
  return { independentContexts: true, parentHistoryShared: false, execute: approval === 'approved', label: { waiting: '承認待ち', approved: '承認済み', denied: '拒否' }[approval] }
}
