export function codingOutcomeFrame(id,phase){
  if(!Object.hasOwn(CODING_OUTCOME_STAGES,id))throw new RangeError('Unknown coding outcome diagram')
  const stages=CODING_OUTCOME_STAGES[id],bounded=clampPhase(phase,stages.length),stage=stageForPhase(bounded,stages.length)
  return {...stages[stage],stage,phase:bounded}
}
export function evaluationComparison(condition){
  if(!['same','prompt','information','attempts'].includes(condition))throw new RangeError('Unknown comparison condition')
  return {comparable:condition==='same',difference:condition}
}
export function costReductionVerdict({consumptionLower,qualityPreserved}){
  return {accepted:consumptionLower===true&&qualityPreserved===true}
}
export function delegatedConsumption(delegated){
  if(typeof delegated!=='boolean')throw new TypeError('Delegation flag must be boolean')
  return {parentContextReduced:delegated,childConsumptionAdded:delegated,totalReductionGuaranteed:false}
}
