export function worldModelUsage(kind) {
  const uses = { environment: [true, false, false], prediction: [false, true, false], infrastructure: [false, false, true], combined: [true, true, true] }
  if (!Object.hasOwn(uses, kind)) throw new RangeError('Unknown world model usage')
  const [environment, prediction, infrastructure] = uses[kind]
  return { environment, prediction, infrastructure, verifiedRealOutcome: false }
}
export function worldEvaluation(role) {
  const concerns = { infrastructure: ['忠実度', '生成効率'], policy: ['予測誤り', '閉ループ遅延', '安全性'] }
  if (!Object.hasOwn(concerns, role)) throw new RangeError('Unknown world model role')
  return [...concerns[role]]
}
