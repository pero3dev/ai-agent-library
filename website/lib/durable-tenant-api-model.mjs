export function durableContractFrame(id,phase){
  if(!Object.hasOwn(DURABLE_CONTRACT_STAGES,id))throw new RangeError('Unknown durable contract diagram')
  const stages=DURABLE_CONTRACT_STAGES[id],bounded=clampPhase(phase,stages.length),stage=stageForPhase(bounded,stages.length)
  return {...stages[stage],stage,phase:bounded}
}
export function tenantContext(mode){
  if(!['verified','missing','generated'].includes(mode))throw new RangeError('Unknown tenant context')
  return {permit:mode==='verified',label:mode==='verified'?'確認済みの文脈を伝播':'実行を閉じる'}
}
export function requestIdempotency(mode){
  if(!['new','match','different'].includes(mode))throw new RangeError('Unknown idempotency case')
  return {create:mode==='new',reject:mode==='different',reuse:mode==='match'}
}
export function approvalScope(mode){
  if(!['same','changed','late'].includes(mode))throw new RangeError('Unknown approval scope')
  return {execute:mode==='same',label:mode==='same'?'同じ対象・条件で再開':mode==='changed'?'新しい対象の承認へ':'旧結果の適用を検証'}
}
