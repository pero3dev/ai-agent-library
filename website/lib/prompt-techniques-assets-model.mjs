export function promptTechniquesAssetsFrame(id,phase){
 if(!Object.hasOwn(PROMPT_TECHNIQUES_ASSETS_STAGES,id))throw new RangeError('Unknown prompt techniques assets diagram')
 const stages=PROMPT_TECHNIQUES_ASSETS_STAGES[id],bounded=clampPhase(phase,stages.length),stage=stageForPhase(bounded,stages.length)
 return {...stages[stage],stage,phase:bounded}
}
export function promptReleaseGate({reviewed,regressionPassed,explicitPromotion,sharedScopeCovered,unusedJudgment}){
 const flags=[reviewed,regressionPassed,explicitPromotion,sharedScopeCovered,unusedJudgment]
 if(flags.some(v=>typeof v!=='boolean'))throw new TypeError('Explicit review regression promotion scope and judgment required')
 return {stagedCandidateReady:flags.every(Boolean),productionChanged:false,qualityGuaranteed:false}
}
