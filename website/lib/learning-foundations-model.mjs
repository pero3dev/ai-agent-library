export function learningFrame(diagram, phase) {
  const definitions = LEARNING_STAGES[diagram]
  if (!definitions) throw new TypeError('Unknown learning diagram')
  const bounded = clampPhase(phase, definitions.length)
  const stage = stageForPhase(bounded, definitions.length)
  return { phase: bounded, stage, ...definitions[stage] }
}

export function causalMask(length) {
  if (![4, 6].includes(length)) throw new RangeError('Length must be 4 or 6')
  return Array.from({ length }, (_, q) => Array.from({ length }, (_, k) => k <= q))
}
export function prefixComparison(change = 'suffix') {
  if (!['front', 'suffix', 'append'].includes(change)) throw new RangeError('Unknown prefix change')
  const original = ['固定1', '固定2', '履歴1', '履歴2', '入力1', '入力2']
  const current = [...original]
  if (change === 'front') current[0] = '変更'
  if (change === 'suffix') current[4] = '変更'
  if (change === 'append') current.push('追記')
  const prefix = change === 'front' ? 0 : change === 'suffix' ? 4 : 6
  return { original, current, prefix, reused: original.map((_, i) => i).slice(0, prefix), recomputed: original.map((_, i) => i).slice(prefix), added: change === 'append' ? [6] : [] }
}
export function demonstrationOrder(axis = 'order', value = 'reverse') {
  if (axis === 'order' && ['original', 'reverse', 'rotate'].includes(value)) return value === 'original' ? ['A', 'B', 'C', 'D'] : value === 'reverse' ? ['D', 'C', 'B', 'A'] : ['B', 'C', 'D', 'A']
  if (axis === 'count' && [2, 3, 4].includes(Number(value))) return ['A', 'B', 'C', 'D'].slice(0, Number(value))
  throw new RangeError('Unknown demonstration setting')
}
export function sparseReconstruction(strength = 1) {
  if (![0, 1, 2].includes(Number(strength))) throw new RangeError('Unknown strength')
  const coefficients = [1, 0, 0, Number(strength), 0, 0, .5, 0]
  // Illustrative linear dictionary with a nonzero residual; not extracted model activations.
  const basis = [[1, 0, 0], [0, 1, 0], [0, 0, 1], [.5, .5, 0], [0, .5, .5], [.5, 0, .5], [0, 0, 1], [1, 1, 1]]
  const reconstructed = [0, 1, 2].map(axis => coefficients.reduce((sum, coefficient, i) => sum + coefficient * basis[i][axis], 0))
  return { coefficients, reconstructed, residual: [.1, -.1, .05], actualModelMeasurement: false }
}
