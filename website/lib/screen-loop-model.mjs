export function loopResponse(reason) {
  const states = {
    complete: { action: '成果物を返す', execute: false, completed: true },
    tool: { action: '検証後に実行', execute: true, completed: false },
    truncated: { action: '途中出力を保存', execute: false, completed: false },
    refused: { action: '拒否を報告', execute: false, completed: false },
    continue: { action: '上限内で再開', execute: false, completed: false }
  }
  if (!Object.hasOwn(states, reason)) throw new RangeError('Unknown response reason')
  return { ...states[reason] }
}
export function screenExecution(approval) {
  if (!['waiting', 'approved', 'denied'].includes(approval)) throw new RangeError('Unknown approval')
  return { execute: approval === 'approved', result: { waiting: '承認待機', approved: '実行して確認', denied: '拒否を報告' }[approval] }
}
export function screenRoute(condition) {
  const routes = { api: ['API', '認可と結果確認'], hybrid: ['API ＋ GUI区間', 'GUIだけを隔離'], gui: ['GUI', '隔離・承認・確認'] }
  if (!Object.hasOwn(routes, condition)) throw new RangeError('Unknown interface condition')
  return [...routes[condition]]
}
